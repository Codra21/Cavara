// Writes migrations/0002_seed_catalog.sql from scripts/seed/catalog-data.ts.
// Run: bun run seed:generate. The output is committed and applied like any other migration.
import { CATEGORIES, PRODUCTS } from "./catalog-data";

const OUT = new URL("../../migrations/0002_seed_catalog.sql", import.meta.url);

/** SQL string literal: single quotes doubled. Values come from our own data file, not user input. */
const q = (value: string | null | undefined) => (value == null ? "NULL" : `'${value.replaceAll("'", "''")}'`);
const n = (value: number | null | undefined) => (value == null ? "NULL" : String(Math.trunc(value)));

const lines: string[] = [
  "-- Generated by scripts/seed/generate-catalog-seed.ts from scripts/seed/catalog-data.ts. Do not edit by hand.",
  "-- Initial catalogue: every product starts published and in stock, in the original display order.",
  "",
];

CATEGORIES.forEach((category, index) => {
  lines.push(
    `INSERT INTO categories (id, name, description, image, sort) VALUES (${q(category.id)}, ${q(category.name)}, ${q(category.description)}, ${q(category.image)}, ${index});`,
  );
});
lines.push("");

PRODUCTS.forEach((product, index) => {
  lines.push(
    `INSERT INTO products (id, slug, name, category_id, summary, details, note, price, status, sort) VALUES (${n(product.id)}, ${q(product.slug)}, ${q(product.name)}, ${q(product.category)}, ${q(product.summary)}, ${q(JSON.stringify(product.details ?? []))}, ${q(product.note)}, ${n(product.price)}, 'published', ${index});`,
  );
  product.variants.forEach((variant, position) => {
    lines.push(
      `INSERT INTO product_variants (product_id, position, name, swatch) VALUES (${n(product.id)}, ${position}, ${q(variant.name)}, ${q(variant.swatch)});`,
    );
    variant.images.forEach((path, imageIndex) => {
      lines.push(
        `INSERT INTO product_images (variant_id, position, path) VALUES ((SELECT id FROM product_variants WHERE product_id = ${n(product.id)} AND position = ${position}), ${imageIndex}, ${q(path)});`,
      );
    });
  });
  lines.push("");
});

await Bun.write(OUT, lines.join("\n"));
console.log(`Wrote ${OUT.pathname} (${CATEGORIES.length} categories, ${PRODUCTS.length} products)`);
